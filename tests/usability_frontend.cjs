"use strict";
const assert = require("node:assert/strict");
const crypto = require("node:crypto");
if (!global.crypto) Object.defineProperty(global,"crypto",{value:crypto.webcrypto});
const {emptyRecord, validateRecord, retestRecord} = require("../experiments/usability/assets/worksheet.js");
const packet = {id:"packet-" + "a".repeat(32), commit:"a".repeat(40), language:"nl", goals:[{id:"execute"},{id:"interpret_partial"}]};
const record = emptyRecord(packet);
let checks = 0;
const check = callback => {callback(); checks++;};
check(() => assert.equal(record.tasks[0].outcome, null));
check(() => assert.ok(Object.values(record.context).every(value => value === null)));
check(() => assert.equal(validateRecord(record,packet,true),record));
const clone = () => JSON.parse(JSON.stringify(record));
check(() => {const value=clone(); value.tasks[0].outcome="passed"; assert.throws(() => validateRecord(value,packet,true));});
check(() => {const value=clone(); value.tasks[0].severity="safe"; assert.throws(() => validateRecord(value,packet,true));});
check(() => {const value=clone(); value.tasks[0].explanation={html:"<script>"}; assert.throws(() => validateRecord(value,packet,true));});
check(() => {const value=clone(); value.context.role="x".repeat(8193); assert.throws(() => validateRecord(value,packet,true));});
check(() => {const value=clone(); value.tasks.push(value.tasks[0]); assert.throws(() => validateRecord(value,packet,true));});
check(() => {const value=clone(); value.tasks[0].id="wrong"; assert.throws(() => validateRecord(value,packet,true));});
check(() => {const value=clone(); value.cloud_url="https://example.invalid"; assert.throws(() => validateRecord(value,packet,true));});
const foreign={...packet,id:"packet-" + "b".repeat(32),commit:"b".repeat(40)};
check(() => assert.throws(() => validateRecord(record,foreign,true)));
record.tasks[0].outcome="blocked";
record.tasks[0].issue="Original observed issue";
const before=JSON.stringify(record);
const retest=retestRecord(record,foreign);
check(() => assert.equal(JSON.stringify(record),before));
check(() => assert.equal(retest.retest_of,record.session_id));
check(() => assert.deepEqual(retest.previous_packet,{id:packet.id,commit:packet.commit}));
check(() => assert.equal(retest.packet_commit,foreign.commit));
check(() => assert.ok(retest.tasks.every(task => task.outcome===null && task.issue===null)));
check(() => assert.ok(Object.values(retest.context).every(value => value===null)));
check(() => assert.notEqual(retest.session_id,record.session_id));
check(() => assert.equal(validateRecord(retest,foreign,true),retest));
const mmtt = {...packet, goals:[{id:"installation"},{id:"startup"},{id:"mmtt_assumptions"},{id:"mmtt_sampling"}]};
const feedback = emptyRecord(mmtt);
check(() => assert.ok(feedback.tasks.every(task => Object.entries(task).every(([key,value]) => key === "id" || value === null))));
feedback.tasks[2].explanation = "INTERNAL QA ONLY: task explanation";
feedback.tasks[2].assistance = "INTERNAL QA ONLY: help";
feedback.context.remaining_limits = "INTERNAL QA ONLY: comments";
check(() => assert.deepEqual(validateRecord(JSON.parse(JSON.stringify(feedback)),mmtt,true),feedback));
check(() => assert.throws(() => validateRecord(feedback,packet,true)));
check(() => assert.throws(() => retestRecord(record,mmtt)));
check(() => assert.ok(retestRecord(feedback,{...mmtt,...foreign,goals:mmtt.goals}).tasks.every(task => task.outcome === null && task.explanation === null)));
console.log(JSON.stringify({passed:true,checks}));
