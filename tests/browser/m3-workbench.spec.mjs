import { createHash } from 'node:crypto';
import { readFile, writeFile, rm } from 'node:fs/promises';
import path from 'node:path';
import { test, expect } from './installed-fixtures.mjs';

test.use({ m3Workbench: true });

test('installed M3: correction, frozen bytes, exact download and reopened relocated evidence', async ({ page, app }, testInfo) => {
  test.setTimeout(180_000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(app.url);
  await expect(page.locator('#candidate-capabilities')).toContainText('CGM comparisons');
  await page.getByLabel('New project name').fill('Frozen synthetic CGM');
  await page.getByRole('button', { name: 'Create project', exact: true }).click();
  await page.locator('#task').selectOption('m3-compare');
  await expect(page.locator('#task-context')).toContainText('30-minute');
  await page.locator('#prepare-form button[type="submit"]').click();
  await expect(page.locator('#freeze-draft')).toBeEnabled();
  await expect(page.locator('#assumptions')).toContainText('not a sandbox');
  await page.locator('#raw-inputs').evaluate(node => { node.open = true; });
  const editor = page.locator('#source-config-json');
  const raw = await editor.inputValue();
  const invalid = JSON.parse(raw); invalid.kind = 'human';
  await editor.fill(JSON.stringify(invalid));
  await expect(page.locator('#draft-status')).toContainText('Saved revision');
  await page.locator('#validate-draft').click();
  await expect(page.locator('#draft-details')).toContainText('Synthetic comparison');
  await expect(page.locator('#freeze-draft')).toBeDisabled();
  await editor.fill(raw);
  await expect(page.locator('#draft-status')).toContainText('Saved revision');
  await page.locator('#validate-draft').click();
  await expect(page.locator('#freeze-draft')).toBeEnabled();
  // Referenced bytes changing after validation must refuse publication.
  const config = JSON.parse(raw), observed = config.people[0].input.file;
  const original = await readFile(observed);
  await writeFile(observed, Buffer.concat([original, Buffer.from('\n')]));
  await page.locator('#freeze-draft').click();
  await expect(page.locator('#notice')).toContainText('changed after validation');
  await expect(page.locator('#plan-select')).toHaveValue('');
  await writeFile(observed, original);
  await page.locator('#validate-draft').click();
  await expect(page.locator('#freeze-draft')).toBeEnabled();
  await page.locator('#freeze-draft').click();
  await expect(page.locator('#run-plan')).toBeEnabled();
  const plan = await page.locator('#plan-select').inputValue();
  const project = await page.locator('#selected-path').textContent();
  const detail = app.command('plan', '--project', project, '--plan', plan);
  expect(detail.task).toBe('m3-compare');
  expect(detail.original_sha256['observations/' + config.people[0].id + '.json']).toBe(createHash('sha256').update(original).digest('hex'));
  // Freeze owns execution: all original observations and predictor folders disappear.
  for (const person of config.people) await rm(person.input.file);
  for (const candidate of config.candidates) await rm(path.dirname(candidate.declaration), { recursive: true });
  await page.locator('#run-plan').click();
  await expect(page.locator('#attempt-list')).toContainText('4/4 planned slots complete');
  await page.getByRole('button', { name: 'Verify saved report', exact: true }).click();
  await expect(page.locator('#report-text')).toContainText('Primary support includes every frozen candidate and persistence');
  const download = page.waitForEvent('download');
  await page.locator('[data-download="report.json"]').click();
  const bytes = await readFile(await (await download).path());
  const report = JSON.parse(bytes);
  expect(report.common.complete_cohort).toBe(true);
  expect(report.common.planned_people).toBe(2);
  const moved = path.join(app.folder, 'moved-project');
  app.command('relocate', '--project', project, '--output', moved);
  await rm(project, { recursive: true });
  await app.restart(); await page.goto(app.url);
  await page.locator('#open-project').evaluate(node => { node.closest('details').open = true; });
  await page.locator('#open-path').fill(moved);
  await page.locator('#open-project button').click();
  await expect(page.locator('#attempt-list')).toContainText('4/4 planned slots complete');
  await page.getByRole('button', { name: 'Verify saved report', exact: true }).click();
  await expect(page.locator('#saved-report')).toBeVisible();
  const repeated = page.waitForEvent('download');
  await page.locator('[data-download="report.json"]').click();
  expect(await readFile(await (await repeated).path())).toEqual(bytes);
  await page.setViewportSize({ width: 520, height: 900 });
  await page.evaluate(() => { document.documentElement.style.fontSize = '200%'; });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('m3-workbench.png'), fullPage: false });
  expect(errors).toEqual([]);
});
